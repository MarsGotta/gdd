    /// Every file under `folder`, at any depth.
    fn every_file(folder: &Path) -> Vec<PathBuf> {
        let mut found = Vec::new();
        for entry in fs::read_dir(folder).unwrap() {
            let path = entry.unwrap().path();
            if path.is_dir() {
                found.extend(every_file(&path));
            } else {
                found.push(path);
            }
        }
        found
    }

