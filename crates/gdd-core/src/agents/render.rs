//! The GDD commands as each agent keeps them: rendered for its sheet from the templates built
//! into the tool, then installed in a project or checked against it, with the instructions of
//! each stack of the project as one more command. Rendering is deterministic: the same tool
//! writes the same bytes. Only the files the sheets name are written.

use std::fs::{self, OpenOptions};
use std::io::{self, ErrorKind, Write};
use std::path::{Path, PathBuf};

use serde_json::Value;

use crate::agents::models::{self, Models};
use crate::agents::sheets::{self, Format, Sheet};
use crate::config::Color;
use crate::stacks;

/// The GDD commands built into the tool, by name: frontmatter with `description: "..."`, then
/// the text, where `{{invoke:<command>}}` marks a call to another command.
const COMMANDS: [(&str, &str); 11] = [
    ("build", include_str!("../../assets/commands/build.md")),
    (
        "build-test",
        include_str!("../../assets/commands/build-test.md"),
    ),
    ("change", include_str!("../../assets/commands/change.md")),
    (
        "discover",
        include_str!("../../assets/commands/discover.md"),
    ),
    ("hotfix", include_str!("../../assets/commands/hotfix.md")),
    ("learn", include_str!("../../assets/commands/learn.md")),
    ("replan", include_str!("../../assets/commands/replan.md")),
    ("report", include_str!("../../assets/commands/report.md")),
    ("review", include_str!("../../assets/commands/review.md")),
    ("setup", include_str!("../../assets/commands/setup.md")),
    ("status", include_str!("../../assets/commands/status.md")),
];

/// The line after the frontmatter of every rendered command.
const GENERATED: &str = "<!-- Generated by `gdd agents install` from gdd's built-in commands. \
                         Edits here are lost: change gdd instead. -->";

/// Where a template marks a call to another command, up to `}}`.
const INVOKE: &str = "{{invoke:";

/// The sheets of the agents to work on: the ones `named` or, when none is, the integrations of
/// `models` (Orchestrator, Builder of each color, Builder in test mode, Reviewer). Each agent
/// once, in that order. An agent without a sheet is an error, and so is no agent at all.
pub fn agents(models: &Models, named: &[String]) -> Result<Vec<Sheet>, String> {
    let names = if named.is_empty() {
        integrations(models)
    } else {
        named.to_vec()
    };
    let mut unique: Vec<&str> = Vec::new();
    for name in &names {
        if !unique.contains(&name.as_str()) {
            unique.push(name);
        }
    }
    if unique.is_empty() {
        let (path, known) = (models::PATH, sheets::NAMES);
        return Err(format!(
            "{path} names no agent: name one with --agent ({known})"
        ));
    }
    let sheet = |name: &&str| sheets::sheet(name).map_err(|e| e.to_string());
    unique.iter().map(sheet).collect()
}

/// The integrations the roles of `models` name, in the order of [`agents`], repeats included.
fn integrations(models: &Models) -> Vec<String> {
    let roles = [Color::Green, Color::Yellow, Color::Red].map(|color| models.roles(color));
    let [green, ..] = &roles;
    let mut tables = vec![&green.orchestrator];
    tables.extend(roles.iter().map(|role| &role.builder));
    tables.extend([&green.builder_test, &green.reviewer_model]);
    tables
        .iter()
        .filter_map(|table| table.get("integration").and_then(Value::as_str))
        .filter(|name| !name.is_empty())
        .map(str::to_string)
        .collect()
}

/// Every GDD command, then the instructions of each of `stacks` as the command
/// `stack-<name>`, for each of `agents`: where it goes, from the project root, and its text. A
/// stack without a sheet is an error.
fn files(agents: &[Sheet], stacks: &[String]) -> Result<Vec<(String, String)>, String> {
    let mut commands: Vec<(String, &str)> = COMMANDS
        .iter()
        .map(|&(command, template)| (command.to_string(), template))
        .collect();
    for stack in stacks {
        let instructions = stacks::instructions(stack).map_err(|e| e.to_string())?;
        commands.push((format!("stack-{stack}"), instructions));
    }
    let mut files = Vec::new();
    for sheet in agents {
        for (command, template) in &commands {
            files.push((sheet.path(command), render(sheet, command, template)?));
        }
    }
    Ok(files)
}

/// `template`, the template of `command`, for the agent of `sheet`: its frontmatter as the
/// sheet's format says, the [`GENERATED`] line, and its text with each call to another command
/// written as the agent makes it. Everything else stays as it is.
fn render(sheet: &Sheet, command: &str, template: &str) -> Result<String, String> {
    let (description, text) = parts(template)
        .ok_or_else(|| format!("the built-in command {command} has no valid frontmatter"))?;
    let description = description.replace('\'', "''");
    let front = match sheet.format() {
        Format::Skill => {
            let name = sheets::name(command);
            format!("---\nname: {name}\ndescription: '{description}'\n---\n")
        }
        Format::Command => format!("---\ndescription: '{description}'\n---\n"),
    };
    Ok(format!("{front}\n{GENERATED}\n\n{}", invoked(sheet, text)))
}

/// The description and the text of a template: `---`, `description: "<description>"` and `---`,
/// each on a line of its own; the text starts at the first line after them that is not empty.
fn parts(template: &str) -> Option<(String, &str)> {
    let rest = template.strip_prefix("---\n")?;
    let (front, text) = rest.split_once("\n---\n")?;
    let quoted = front.strip_prefix("description: ")?;
    let description = serde_json::from_str(quoted).ok()?;
    Some((description, text.trim_start_matches('\n')))
}

/// `text` with each `{{invoke:<command>}}` written as the agent of `sheet` calls that command.
fn invoked(sheet: &Sheet, text: &str) -> String {
    let mut written = String::new();
    let mut rest = text;
    while let Some(at) = rest.find(INVOKE) {
        let after = &rest[at + INVOKE.len()..];
        let Some(end) = after.find("}}") else {
            break;
        };
        written.push_str(&rest[..at]);
        written.push_str(&sheet.invoke(&after[..end]));
        rest = &after[end + 2..];
    }
    written.push_str(rest);
    written
}

/// Writes every GDD command and the instructions of each of `stacks` for each of `agents` in the
/// project at `root`, creating their folders, and touches no other file: the paths it wrote,
/// from the root. It writes nothing when a stack has no sheet, or when a symbolic link on the
/// way to any of them would send a command elsewhere.
pub fn install(root: &Path, agents: &[Sheet], stacks: &[String]) -> Result<Vec<String>, String> {
    let files = files(agents, stacks)?;
    for (path, _) in &files {
        let cannot = |why: String| format!("cannot write {path}: {why}");
        match first_link(root, path) {
            Ok(None) => {}
            Ok(Some(link)) => return Err(cannot(not_followed(&link))),
            Err(e) => return Err(cannot(e.to_string())),
        }
    }
    for (path, text) in &files {
        replace(root, path, text).map_err(|e| format!("cannot write {path}: {e}"))?;
    }
    Ok(files.into_iter().map(|(path, _)| path).collect())
}

/// Writes `text` as the file `path` of the project at `root`, creating its folders. The file is
/// always a new one in place of the old: when the old one shares its data with another file (a
/// hard link), the other keeps what it had.
fn replace(root: &Path, path: &str, text: &str) -> io::Result<()> {
    let file = root.join(path);
    if let Some(folder) = file.parent() {
        fs::create_dir_all(folder)?;
    }
    match fs::remove_file(&file) {
        Ok(()) => {}
        Err(e) if e.kind() == ErrorKind::NotFound => {}
        Err(e) => return Err(e),
    }
    let mut new = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&file)?;
    new.write_all(text.as_bytes())
}

/// The first symbolic link on the way from `root` to `path`, `path` itself included. Only the
/// part of the way that exists is looked at: what is still to be made holds no link.
fn first_link(root: &Path, path: &str) -> io::Result<Option<PathBuf>> {
    let mut part = PathBuf::new();
    for component in Path::new(path).components() {
        part.push(component);
        match fs::symlink_metadata(root.join(&part)) {
            Ok(meta) if meta.file_type().is_symlink() => return Ok(Some(part)),
            Ok(_) => {}
            Err(e) if e.kind() == ErrorKind::NotFound => return Ok(None),
            Err(e) => return Err(e),
        }
    }
    Ok(None)
}

/// Why gdd keeps no command behind `link`, and what to do about it.
fn not_followed(link: &Path) -> String {
    let link = link.display();
    format!(
        "{link} is a symbolic link, which gdd does not write through: remove the link and \
         install again"
    )
}

/// What is wrong with the GDD commands and the instructions of each of `stacks` of `agents` in
/// the project at `root`: one line for each file that is missing, behind a symbolic link
/// [`install`] would not write through, or does not hold exactly what [`install`] writes.
pub fn check(root: &Path, agents: &[Sheet], stacks: &[String]) -> Result<Vec<String>, String> {
    let mut problems = Vec::new();
    for (path, text) in files(agents, stacks)? {
        let link = first_link(root, &path).map_err(|e| format!("cannot read {path}: {e}"))?;
        if let Some(link) = link {
            problems.push(format!("{path}: {}", not_followed(&link)));
            continue;
        }
        match fs::read(root.join(&path)) {
            Ok(bytes) if bytes == text.as_bytes() => {}
            Ok(_) => problems.push(format!("{path}: differs from what gdd writes")),
            Err(e) if e.kind() == ErrorKind::NotFound => problems.push(format!("{path}: missing")),
            Err(e) => return Err(format!("cannot read {path}: {e}")),
        }
    }
    Ok(problems)
}

