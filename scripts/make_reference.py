#!/usr/bin/env python3
"""Writes docs/reference/cli.md, and its Spanish twin docs/es/reference/cli.md, from the help of
the gdd binary (the help itself is in English in both).

    python3 scripts/make_reference.py            # write the page
    python3 scripts/make_reference.py --check    # fail when the page is out of date

The binary is target/release/gdd, else target/debug/gdd, else `gdd` on the PATH; GDD_BIN
chooses another. Change the help text in the code (crates/gdd/src/lib.rs), never the page.
"""

import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGES = {"en": ROOT / "docs" / "reference" / "cli.md", "es": ROOT / "docs" / "es" / "reference" / "cli.md"}


GROUPS = [
    ("Set up a project", ["init", "bootstrap", "adopt", "agents", "stacks", "upgrade"]),
    ("Plan and approve", ["new-change", "classify", "gate", "sitting", "note", "changelog-line"]),
    ("Build and release", ["launch", "resume", "park", "prepare", "merge", "release"]),
    ("Gates and checks", ["g2", "g3", "guard", "snapshot", "scope", "selftest", "ci"]),
    ("See where things stand", ["status", "board", "inbox", "report", "learn", "changelog", "session"]),
]

WORDS = {
    "en": {
        "title": "Command reference",
        "intro": "Every command of `gdd`, with its options, as `gdd <command> --help` prints them.",
        "note": [
            "> Generated by `scripts/make_reference.py` from {version}. Do not edit this page:",
            "> change the help text in the code and run the script again.",
        ],
        "board": [
            "Run `gdd` with no arguments in a terminal to open the [Board](#gdd-board). In a project,",
            "use `bin/gdd`: it runs the gdd built for that project.",
        ],
        "groups": [title for title, _ in GROUPS],
        "see_also": [
            "## See also",
            "",
            "- [Configuration](configuration.md): the files in `gdd/` these commands read.",
            "- [Environment variables](environment.md): what gdd reads from the environment.",
            "- [Files gdd writes](files.md): the records, log and inbox under `.gdd/`.",
        ],
    },
    "es": {
        "title": "Referencia de comandos",
        "intro": "Todos los comandos de `gdd`, con sus opciones, tal como los imprime `gdd <comando> --help`.\n"
        "La ayuda de gdd está en inglés, como la herramienta.",
        "note": [
            "> Generada por `scripts/make_reference.py` a partir de {version}. No edites esta página:",
            "> cambia el texto de ayuda en el código y vuelve a ejecutar el script.",
        ],
        "board": [
            "Ejecuta `gdd` sin argumentos en una terminal para abrir el [Board](#gdd-board). En un",
            "proyecto, usa `bin/gdd`: ejecuta el gdd construido para ese proyecto.",
        ],
        "groups": ["Preparar un proyecto", "Planificar y aprobar", "Construir y publicar",
                   "Puertas y comprobaciones", "Ver cómo va todo"],
        "see_also": [
            "## Ver también",
            "",
            "- [Configuración](configuration.md): los ficheros de `gdd/` que leen estos comandos.",
            "- [Variables de entorno](environment.md): lo que gdd lee del entorno.",
            "- [Ficheros que escribe gdd](files.md): los registros, el log y la bandeja de `.gdd/`.",
        ],
    },
}


def binary() -> str:
    chosen = os.environ.get("GDD_BIN")
    if chosen:
        return chosen
    for build in ("release", "debug"):
        path = ROOT / "target" / build / "gdd"
        if path.is_file():
            return str(path)
    found = shutil.which("gdd")
    if not found:
        sys.exit("no gdd binary: build it (cargo build --release) or set GDD_BIN")
    return found


def help_of(gdd: str, words: list[str]) -> str:
    done = subprocess.run([gdd, *words, "--help"], capture_output=True, text=True, check=True)
    return done.stdout.rstrip() + "\n"


def commands_in(text: str) -> list[str]:
    block = re.search(r"^Commands:\n(.*?)(?:\n\n|\Z)", text, re.S | re.M)
    if not block:
        return []
    names = [line.split()[0] for line in block.group(1).splitlines() if line.startswith("  ")]
    return [name for name in names if name != "help"]


def section(gdd: str, words: list[str], level: int) -> list[str]:
    text = help_of(gdd, words)
    about, _, rest = text.partition("\n\nUsage:")
    lines = [f"{'#' * level} gdd {' '.join(words)}", "", about.strip(), ""]
    lines += ["```text", "Usage:" + rest.rstrip(), "```", ""]
    for sub in commands_in(text):
        lines += section(gdd, [*words, sub], level + 1)
    return lines


def page(gdd: str, lang: str = "en") -> str:
    top = help_of(gdd, [])
    every = commands_in(top)
    grouped = [name for _, names in GROUPS for name in names]
    missing = [name for name in every if name not in grouped]
    if missing:
        sys.exit(f"add these commands to GROUPS in {Path(__file__).name}: {', '.join(missing)}")
    version = subprocess.run([gdd, "--version"], capture_output=True, text=True).stdout.strip()
    w = WORDS[lang]
    titles = w["groups"]
    lines = [f"# {w['title']}", "", w["intro"], "", "> [!NOTE]"]
    lines += [line.format(version=version or "gdd") for line in w["note"]]
    lines += ["", *w["board"], ""]
    for title, (_, names) in zip(titles, GROUPS):
        lines.append(f"**{title}:** " + " · ".join(f"[`{n}`](#gdd-{n})" for n in names if n in every))
        lines.append("")
    for title, (_, names) in zip(titles, GROUPS):
        lines += [f"## {title}", ""]
        for name in names:
            if name in every:
                lines += section(gdd, [name], 3)
    lines += [*w["see_also"], ""]
    return "\n".join(lines)


def main() -> None:
    gdd = binary()
    stale = []
    for lang, path in PAGES.items():
        text = page(gdd, lang)
        name = path.relative_to(ROOT)
        if "--check" in sys.argv[1:]:
            if not path.is_file() or path.read_text() != text:
                stale.append(str(name))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {name}")
    if stale:
        sys.exit(f"out of date: {', '.join(stale)}: run scripts/make_reference.py")
    if "--check" in sys.argv[1:]:
        print("The command reference is up to date.")


if __name__ == "__main__":
    main()
