def binary() -> str:
    chosen = os.environ.get("GDD_BIN")
    if chosen:
        return chosen
    for build in ("release", "debug"):
        path = ROOT / "target" / build / "gdd"
        if path.is_file():
            return str(path)
    found = shutil.which("gdd")
    if not found:
        sys.exit("no gdd binary: build it (cargo build --release) or set GDD_BIN")
    return found


def help_of(gdd: str, words: list[str]) -> str:
    done = subprocess.run([gdd, *words, "--help"], capture_output=True, text=True, check=True)
    return done.stdout.rstrip() + "\n"


def blocks(text: str) -> dict[str, list[str]]:
    """The about paragraph, the usage and each `Title:` list of a clap help, by title."""
    about, _, rest = text.partition("\n\nUsage:")
    found = {"about": [about.strip()], "Usage": ["Usage:" + rest.split("\n\n", 1)[0]]}
    for match in re.finditer(r"^(\w[\w ]*):\n((?:[ \t]+.*\n?)+)", rest, re.M):
        found[match.group(1)] = match.group(2).rstrip("\n").splitlines()
    return found


def entries(lines: list[str]) -> list[tuple[str, str]]:
    """The (term, description) pairs of a clap list; a line indented past the terms continues
    the description above it."""
    pairs: list[tuple[str, str]] = []
    for line in lines:
        indent = len(line) - len(line.lstrip())
        match = re.match(r"^\s+(\S.*?)(?:\s{2,}(\S.*))?$", line)
        if pairs and indent > 10 and not line.lstrip().startswith("-"):
            term, desc = pairs[-1]
            pairs[-1] = (term, f"{desc} {line.strip()}".strip())
        elif match:
            pairs.append((match.group(1), match.group(2) or ""))
    return pairs


def subcommands(text: str) -> list[tuple[str, str]]:
    found = [(term.split()[0], desc) for term, desc in entries(blocks(text).get("Commands", []))]
    return [(name, desc) for name, desc in found if name != "help"]


def page_of(words: list[str]) -> str:
    return "-".join(words)


def sentence(text: str) -> str:
    text = text.strip()
    return text if not text or text[-1] in ".!?" else text + "."


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def describe(desc: str, w: dict) -> str:
    """A clap description for a table cell: its words, then its default and possible values."""
    extra = []
    default = re.search(r'\s*\[default: ((?:"[^"]*")|[^\]]*)\]', desc)
    if default:
        extra.append(w["default"].format(value=f"`{default.group(1)}`"))
        desc = desc.replace(default.group(0), "")
    possible = re.search(r"\s*\[possible values: ([^\]]*)\]", desc)
    if possible:
        values = ", ".join(f"`{v.strip()}`" for v in possible.group(1).split(","))
        extra.append(w["possible"].format(values=values))
        desc = desc.replace(possible.group(0), "")
    return cell(" ".join([sentence(desc), *extra]).strip())


def wrap(text: str) -> list[str]:
    """`text` in lines of at most WIDTH columns, never breaking a link or inline code."""
    keep = re.sub(r"\[[^\]]*\]\([^)]*\)|`[^`]*`", lambda m: m.group(0).replace(" ", "\0"), text)
    lines = textwrap.wrap(keep, WIDTH, break_long_words=False, break_on_hyphens=False)
    return [line.replace("\0", " ") for line in lines]


def read_note(page: str) -> tuple[dict[str, str], dict[str, str]]:
    """The header (summary, runs) and the sections of scripts/cli_notes/<page>.md."""
    path = NOTES / f"{page}.md"
    name = path.relative_to(ROOT)
    if not path.is_file():
        sys.exit(f"missing {name}: write who runs `gdd {page}` and its examples")
    text = path.read_text(encoding="utf-8")
    header = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not header:
        sys.exit(f"{name}: no header (---, summary: ..., runs: ..., ---)")
    meta = dict(line.split(": ", 1) for line in header.group(1).splitlines() if ": " in line)
    for key in ("summary", "runs"):
        if not meta.get(key):
            sys.exit(f"{name}: the header has no {key}")
    for who in meta["runs"].split(", "):
        if who not in RUNS:
            sys.exit(f"{name}: runs `{who}`, not one of: {', '.join(RUNS)}")
    found: dict[str, list[str]] = {}
    title, fenced = None, False
    for line in text[header.end():].splitlines():
        if re.match(r"^\s*(```|~~~)", line):
            fenced = not fenced
        if not fenced and line.startswith("## "):
            title = line[3:].strip()
            if title not in NOTE_SECTIONS or title in found:
                sys.exit(f"{name}: unexpected section `## {title}`")
            found[title] = []
        elif title:
            found[title].append(line)
        elif line.strip():
            sys.exit(f"{name}: text before its first section")
    sections = {title: "\n".join(lines).strip() for title, lines in found.items()}
    for title in NOTE_SECTIONS[:2]:
        if title not in sections:
            sys.exit(f"{name}: no `## {title}` section")
    return meta, sections


def every_command(gdd: str) -> list[list[str]]:
    """Every command, in the order of GROUPS, each followed by its subcommands."""
    every = [name for name, _ in subcommands(help_of(gdd, []))]
    grouped = [name for _, names in GROUPS for name in names]
    missing = [name for name in every if name not in grouped]
    if missing:
        sys.exit(f"add these commands to GROUPS in {Path(__file__).name}: {', '.join(missing)}")
    out = []
    for name in grouped:
        if name in every:
            out.append([name])
            out += [[name, sub] for sub, _ in subcommands(help_of(gdd, [name]))]
    return out


def link(words: list[str]) -> str:
    return f"[`gdd {' '.join(words)}`]({page_of(words)}.md)"


def table(head: tuple[str, str], rows: list[tuple[str, str]]) -> list[str]:
    return [f"| {head[0]} | {head[1]} |", "|---|---|", *(f"| {a} | {b} |" for a, b in rows), ""]


def command_page(words: list[str], helps: dict, notes: dict, version: str, lang: str) -> str:
    w = WORDS[lang]
    page = page_of(words)
    found = blocks(helps[page])
    comment = wrap(w["page_note"].format(version=version, page=page))
    lines = [f"# gdd {' '.join(words)}", "", "<!--", *comment, "-->", ""]
    lines += [*wrap(sentence(found["about"][0])), ""]
    lines += [f"## {w['usage']}", "", "```text", found["Usage"][0], "```", ""]
    arguments = entries(found.get("Arguments", []))
    if arguments:
        rows = [(f"`{cell(term)}`", describe(desc, w)) for term, desc in arguments]
        lines += [f"## {w['arguments']}", "", *table((w["argument"], w["description"]), rows)]
    options = [(term, desc) for term, desc in entries(found.get("Options", []))
               if not term.endswith(("--help", "--version"))]
    lines += [f"## {w['options']}", ""]
    if options:
        rows = [(f"`{cell(term)}`", describe(desc, w)) for term, desc in options]
        lines += table((w["option"], w["description"]), rows)
    else:
        lines += [w["no_options"], ""]
    subs = subcommands(helps[page])
    if subs:
        rows = [(link([*words, sub]), describe(desc, w)) for sub, desc in subs]
        lines += [f"## {w['subcommands']}", "", *table((w["subcommand"], w["description"]), rows)]
    _, sections = notes[page]
    for title in NOTE_SECTIONS[:2]:
        lines += [f"## {w['sections'][title]}", "", sections[title], ""]
    see = [w["index_link"]]
    if len(words) > 1:
        see.append(w["parent_link"].format(parent=" ".join(words[:-1]), page=page_of(words[:-1])))
    lines += [f"## {w['sections']['See also']}", "", *(f"- {item}" for item in see)]
    if "See also" in sections:
        lines.append(sections["See also"])
    lines.append("")
    return "\n".join(lines)


def who_runs(runs: str, w: dict) -> str:
    said = ", ".join(w["runs"][who] for who in runs.split(", "))
    return said[:1].upper() + said[1:]


def index_page(commands: list[list[str]], helps: dict, notes: dict, version: str,
               lang: str) -> str:
    w = WORDS[lang]
    lines = [f"# {w['title']}", "", *w["intro"], "",
             *(line.format(version=version) for line in w["note"]), ""]
    for title, (_, names) in zip(w["groups"], GROUPS):
        lines += [f"## {title}", "", "| " + " | ".join(w["columns"]) + " |", "|---|---|---|"]
        for words in commands:
            if words[0] in names:
                meta, _ = notes[page_of(words)]
                lines.append(f"| {link(words)} | {cell(meta['summary'])} | "
                             f"{who_runs(meta['runs'], w)} |")
        lines.append("")
    about = {page_of(words): blocks(helps[page_of(words)])["about"][0] for words in commands}
    json = ", ".join(link(words) for words in commands if "JSON" in about[page_of(words)])
    refused = ", ".join(link(words) for words in commands
                        if "Builders and Reviewers cannot" in about[page_of(words)])
    for line in w["global"]:
        filled = line.replace("{json}", json).replace("{refused}", refused)
        lines += wrap(filled) if filled != line else [line]
    lines += [*w["see_also"], ""]
    return "\n".join(lines)


