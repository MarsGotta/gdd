def slug(heading: str) -> str:
    """The GitHub anchor of a heading."""
    text = re.sub(r"<[^>]+>", "", heading)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = text.replace("`", "").replace("*", "").lower().strip()
    return "".join(c for c in text if c.isalnum() or c in " -_").replace(" ", "-")


def anchors(path: Path) -> list[str]:
    """The anchors of the headings of a page, in order, outside code blocks."""
    out, fenced, seen = [], False, {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if FENCE.match(line):
            fenced = not fenced
            continue
        m = None if fenced else HEADING.match(line)
        if m:
            s = slug(m.group(1))
            n = seen.get(s, 0)
            seen[s] = n + 1
            out.append(s if n == 0 else f"{s}-{n}")
    return out


def spanish_anchors(page: Path, text: str) -> str:
    """The notes are English, so their links name English anchors: in a Spanish page, each one
    becomes the anchor of the same heading (by position) of the Spanish page it points to."""
    es_root, en_root = FOLDERS["es"].parent.parent, FOLDERS["en"].parent.parent

    def fix(m: re.Match[str]) -> str:
        target, anchor = m.group(1), m.group(2)
        dest = (page.parent / target).resolve() if target else None
        if dest is None or not dest.is_file():
            return m.group(0)
        en = en_root / dest.relative_to(es_root.resolve())
        if not en.is_file():
            return m.group(0)
        theirs, ours = anchors(en), anchors(dest)
        if anchor in ours or len(theirs) != len(ours) or anchor not in theirs:
            return m.group(0)
        return f"]({target}#{ours[theirs.index(anchor)]})"

    lines, fenced = text.split("\n"), False
    for i, line in enumerate(lines):
        if FENCE.match(line):
            fenced = not fenced
        elif not fenced:
            lines[i] = ANCHORED.sub(fix, line)
    return "\n".join(lines)


def pages(gdd: str) -> dict[Path, str]:
    """Every page to write, by path, in both languages."""
    version = subprocess.run([gdd, "--version"], capture_output=True, text=True).stdout.strip()
    version = version or "gdd"
    commands = every_command(gdd)
    helps = {page_of(words): help_of(gdd, words) for words in commands}
    notes = {page: read_note(page) for page in helps}
    strays = sorted(p.stem for p in NOTES.glob("*.md") if p.stem not in helps)
    if strays:
        sys.exit(f"notes of no command in scripts/cli_notes/: {', '.join(strays)}")
    out = {}
    for lang, folder in FOLDERS.items():
        out[folder / "index.md"] = index_page(commands, helps, notes, version, lang)
        for words in commands:
            out[folder / f"{page_of(words)}.md"] = command_page(words, helps, notes, version, lang)
    for path in [p for p in out if FOLDERS["es"] in p.parents]:
        out[path] = spanish_anchors(path, out[path])
    return out


def main() -> None:
    wanted = pages(binary())
    present = {p for folder in FOLDERS.values() for p in folder.glob("*.md")}
    gone = sorted(present - set(wanted)) + [p for p in OLD.values() if p.is_file()]
    if "--check" in sys.argv[1:]:
        stale = [p for p, text in wanted.items() if not p.is_file() or p.read_text() != text]
        if stale or gone:
            names = ", ".join(str(p.relative_to(ROOT)) for p in [*stale, *gone])
            sys.exit(f"out of date: {names}: run scripts/make_reference.py")
        print(f"The CLI reference is up to date: {len(wanted)} pages.")
        return
    for path, text in wanted.items():
        if not path.is_file() or path.read_text() != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    for path in gone:
        path.unlink()
        print(f"removed {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
